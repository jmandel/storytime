// The parent's phone remembers its setup, its readers and the last call per reader; settings edit them;
// "Forget this device" clears everything.
import {browser, page, check, URL_, LK} from './lib.mjs'
const phone = await page(390, 844, true)
phone.on('dialog', d => d.accept())
const startText = () => phone.textContent('#startText')
const chips = () => phone.locator('#readers .chip:not(.add)').allTextContents()
const fresh = async () => { await phone.goto(URL_); await phone.reload(); await phone.waitForSelector('#startShelf button', {timeout: 10000}).catch(() => {}) }

await phone.goto(URL_)
await phone.waitForSelector('#startShelf button')
const publicTitles = await phone.locator('#startShelf button').allTextContents()
check(publicTitles.length > 0 && await phone.isVisible('#keyHint'), `a fresh device shows the public books: ${publicTitles}`)

await phone.goto(`${URL_}#lk=${LK}&reader=Gramma,Grammie&child=Cleo`)
await phone.waitForSelector('#startShelf button')
await fresh()
check(await phone.locator('#startShelf button').count() > publicTitles.length, 'bare address shows the private books after the home link was opened once')
check(!(await phone.evaluate(() => location.hash)).includes('lk='), 'key is not put back into the address bar')
check(JSON.stringify(await chips()) === '["Gramma","Grammie"]', `readers from the home link: ${await chips()}`)
check((await startText()).startsWith("Gramma's link"), `first reader preselected: "${await startText()}"`)

await phone.evaluate(() => { window.noReload = true })
await phone.locator('#readers .chip', {hasText: 'Grammie'}).click(); await phone.waitForSelector('#startShelf button')
check((await startText()).includes('Grammie'), `picking a reader: "${await startText()}"`)
check(await phone.evaluate(() => window.noReload === true), 'switching readers updates in place (no page reload)')
await phone.click('#startBtn')
const link = new URLSearchParams((await phone.textContent('#linkbox')).split('#')[1])
check(link.get('lk') === LK && link.get('reader') === 'Grammie' && link.get('child') === 'Cleo', 'call link carries the key and only the chosen reader')
check(!link.has('as') && !link.has('b'), 'the link names no side and no books, so both sides can open it')
const roomNow = async () => new URLSearchParams((await phone.evaluate(() => location.hash)).slice(1)).get('r')
await phone.click('#leaveBtn'); await phone.waitForSelector('#startBtn')
check((await startText()).includes('Grammie'), 'after leaving, the same reader is still selected')
await phone.click('#startBtn'); await phone.waitForSelector('#leaveBtn')
check(await roomNow() === link.get('r'), 'calling the same reader again opens the same call')
await phone.click('#leaveBtn'); await phone.waitForSelector('#startBtn')
await phone.locator('#readers .chip', {hasText: 'Gramma'}).first().click(); await phone.click('#startBtn'); await phone.waitForSelector('#leaveBtn')
const grammaRoom = await roomNow()
check(grammaRoom !== link.get('r'), 'each reader has their own call')
await phone.click('#leaveBtn'); await phone.waitForSelector('#startBtn')
await phone.click('#settingsBtn'); await phone.click('#settingsNewLink'); await phone.waitForSelector('#startBtn')
await phone.click('#startBtn'); await phone.waitForSelector('#leaveBtn')
check(await roomNow() !== grammaRoom, '"New link for Gramma" replaces her call')
await phone.click('#leaveBtn'); await phone.waitForSelector('#startBtn')
await phone.evaluate(() => {
  Object.defineProperty(navigator, 'share', {value: undefined})
  navigator.clipboard.writeText = async t => { window.copied = t }
  window.alert = () => {}
})
await phone.click('#settingsBtn'); await phone.click('#settingsHome'); await phone.waitForFunction(() => window.copied)
const home = await phone.evaluate(() => window.copied)
await phone.click('#settingsClose')
const other = await page(390, 844, true)
await other.goto(home); await other.waitForSelector('#readers .chip')
await other.locator('#readers .chip', {hasText: 'Grammie'}).click(); await other.click('#startBtn'); await other.waitForSelector('#leaveBtn')
check(new URLSearchParams((await other.evaluate(() => location.hash)).slice(1)).get('r') === link.get('r'),
  "another parent device set up from the home link calls the same room")
await other.close()
await fresh()
await phone.click('#readers .chip.add'); await phone.fill('#newReader', 'Nana'); await phone.press('#newReader', 'Enter')
await phone.waitForSelector('#readers .chip.add')
check(JSON.stringify(await chips()) === '["Gramma","Grammie","Nana"]' && (await startText()).includes('Nana'), `adding a reader: ${await chips()}`)
await phone.click('#settingsBtn'); await phone.fill('#set_readers', 'Gramma\nNana'); await phone.click('#settingsSave')
await phone.waitForSelector('#startShelf button')
check(JSON.stringify(await chips()) === '["Gramma","Nana"]', `settings edit the readers: ${await chips()}`)
await phone.click('#settingsBtn'); await phone.click('#settingsForget')
await phone.waitForTimeout(1000)
check(await phone.locator('#startShelf button').count() === publicTitles.length && await phone.isVisible('#keyHint')
  && await phone.locator('#readers .chip:not(.add)').count() === 0, 'forget clears the setup (public books only, no readers)')
await browser.close()
