// Collections: a story is chosen from the collection's contents, opens on the reader's tablet with the collection's
// title, and the phone shows it. Speakers are colors only (no name labels); names in narration share the color.
import {browser, page, check, URL_, LK} from './lib.mjs'
const child = await page(390, 844, true), reader = await page(1180, 820)
await child.goto(`${URL_}#lk=${LK}&reader=Grandma&child=Cleo`)
await child.waitForSelector('#startShelf button')
const col = child.locator('#startShelf button', {hasText: 'Frog and Toad'})
check(await col.count() === 1 && (await col.textContent()).includes('story'), `collection card: ${await col.textContent()}`)
await col.click()
const stories = await child.locator('#startShelf .storyList button').allTextContents()
check(stories.some(s => s.includes('Ice Cream')), `contents: ${stories}`)
await child.locator('#startShelf .storyList button', {hasText: 'Ice Cream'}).click()
await child.click('#startShelf .back')
await child.click('#startBtn')
const link = await child.textContent('#linkbox')
check(new URLSearchParams(link.split('#')[1]).get('b') === 'frog-and-toad/ice-cream', 'story id in tonight\'s stack')
await child.click('#goBtn'); await child.waitForSelector('#joinBtn'); await child.click('#joinBtn')
await reader.goto(link); await reader.click('#joinBtn'); await reader.waitForSelector('#strip img')
check((await reader.textContent('#bookTitle')) === 'Frog and Toad · Ice Cream', `reader title: ${await reader.textContent('#bookTitle')}`)
check((await reader.textContent('#shelfBtn')) === 'Contents', 'shelf button says Contents inside a collection')
check((await reader.textContent('#pageNum')) === 'Page 158', `printed page numbers: ${await reader.textContent('#pageNum')}`)
check(await reader.locator('.who').count() === 0 && await reader.locator('#pageText .said').count() > 0, 'speakers in color, no name labels')
check(await reader.locator('#pageText .named').count() > 0, `speaker names in narration colored: ${await reader.locator('#pageText .named').allTextContents()}`)
await child.waitForFunction(() => document.getElementById('pageBadge'), null, {timeout: 45000}).catch(() => {})
check((await child.textContent('#pageBadge') || '').includes('Frog and Toad: Ice Cream'), `phone badge: ${await child.textContent('#pageBadge')}`)
await reader.click('#shelfBtn')
check(await reader.locator('#shelf .storyList button.cur').count() === 1, 'Contents opens on the collection with the story marked')
await browser.close()
